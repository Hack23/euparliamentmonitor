// Normalise legacy `news/*.html` articles in place — idempotent at the byte
// level so re-runs on already-normalised articles leave the file untouched
// and `aws s3 sync` (size+mtime) can correctly skip them.
//
// Replaces the inline `sed -i` loops previously embedded in
// `.github/workflows/deploy-s3.yml`. `sed -i` always rewrites the file —
// even when the substitution produced zero changes — which bumps mtime
// and forces every legacy article to re-upload on every deploy.
//
// Two normalisations applied to each `news/*.html` file:
//
//   1. Convert legacy per-article CSPs to the current fixed policy
//      (`script-src 'self'` with all executable inline blocks externalised
//      to `js/article-runtime.js`):
//        - `default-src 'none'`  → `default-src 'self'`
//        - `connect-src 'none'`  → `connect-src 'self'`
//        - `script-src 'self' 'sha256-…' 'sha256-…' …;` → `script-src 'self';`
//
//   2. Pin the Mermaid bundle cache-bust to the version declared in
//      `package.json` so a Mermaid devDependency bump invalidates browser
//      and CloudFront caches across ALL articles on the next deploy —
//      including legacy articles that aren't regenerated by the
//      aggregator pipeline.
//
//      The Mermaid filename / filepath contract is preserved exactly:
//      `<script src="../js/mermaid-init.js?v=<MERMAID_VERSION>">`. Every
//      existing reference resolves identically; only the `?v=…` query
//      changes when the pinned mermaid version changes.
//
// Idempotency contract:
//   - If both rewrites produce content identical to what's already on disk,
//     the file is left untouched (mtime preserved → S3 skip).
//   - Re-running with the same MERMAID_VERSION on already-normalised
//     articles is a byte-level no-op.
//
// Exit codes:
//   0 — success (some files may have been rewritten, others left alone).
//   1 — could not resolve MERMAID_VERSION from package.json.

import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, '..');

// ─── Resolve Mermaid version (cache-bust query) ─────────────────────────
let mermaidVersion = '';
try {
  const pkg = JSON.parse(readFileSync(join(repoRoot, 'package.json'), 'utf8'));
  const raw = pkg?.devDependencies?.mermaid;
  if (typeof raw === 'string' && raw.trim() !== '') {
    mermaidVersion = raw.replace(/^[\^~><=\s]+/, '').trim();
  }
} catch (e) {
  console.error(`❌ Failed to read mermaid version from package.json: ${e instanceof Error ? e.message : String(e)}`);
  process.exit(1);
}
if (!mermaidVersion) {
  console.error('❌ Could not resolve mermaid version from package.json (devDependencies.mermaid).');
  process.exit(1);
}
console.log(`🔧 Pinning Mermaid cache-bust query to v${mermaidVersion}`);

// ─── Collect news/*.html ─────────────────────────────────────────────────
const newsDir = join(repoRoot, 'news');
let files = [];
try {
  files = readdirSync(newsDir)
    .filter((f) => f.endsWith('.html'))
    .map((f) => join(newsDir, f));
} catch {
  console.log('ℹ️  news/ directory does not exist — nothing to normalise.');
  process.exit(0);
}

// ─── Rewrite rules ───────────────────────────────────────────────────────
function normaliseCsp(content) {
  let out = content;
  // 1a. default-src 'none' → default-src 'self'
  out = out.replaceAll("default-src 'none'", "default-src 'self'");
  // 1b. connect-src 'none' → connect-src 'self'
  out = out.replaceAll("connect-src 'none'", "connect-src 'self'");
  // 1c. Collapse `script-src 'self' 'sha256-…' 'sha256-…' …;` → `script-src 'self';`
  out = out.replace(
    /script-src 'self'(?: 'sha256-[^']+')+;/g,
    "script-src 'self';"
  );
  return out;
}

function pinMermaidVersion(content, version) {
  // Match any existing mermaid-init.js reference (with or without an
  // existing ?v=<x> query) and rewrite it to the current version.
  // Idempotent: re-running with the same version leaves the file
  // byte-identical.
  return content.replace(
    /src="\.\.\/js\/mermaid-init\.js(\?v=[0-9.]+)?"/g,
    `src="../js/mermaid-init.js?v=${version}"`
  );
}

// ─── Process files ───────────────────────────────────────────────────────
let cspRewritten = 0;
let mermaidRewritten = 0;
let unchanged = 0;
let written = 0;

for (const filePath of files) {
  const original = readFileSync(filePath, 'utf8');
  let next = normaliseCsp(original);
  const cspChanged = next !== original;
  const beforeMermaid = next;
  next = pinMermaidVersion(next, mermaidVersion);
  const mermaidChanged = next !== beforeMermaid;

  if (next === original) {
    unchanged++;
    continue;
  }
  // Only write when content actually differs from disk — preserves mtime
  // for already-normalised files and keeps `aws s3 sync` honest.
  writeFileSync(filePath, next, 'utf8');
  written++;
  if (cspChanged) cspRewritten++;
  if (mermaidChanged) mermaidRewritten++;
}

console.log(
  `✅ Normalised ${files.length} legacy article(s): ` +
    `${written} written (${cspRewritten} CSP, ${mermaidRewritten} Mermaid pin), ` +
    `${unchanged} unchanged — mtime preserved so aws s3 sync will skip them.`
);
